-- V1__criar_tabelas.sql
-- Esquema inicial do Sistema de Chamados de Suporte do IFRN.
--
-- O Hibernate NAO cria tabelas (spring.jpa.hibernate.ddl-auto=validate): o esquema
-- versionado aqui e a unica fonte de verdade. Uma migration ja aplicada nunca e editada;
-- qualquer correcao entra em uma nova versao (V4__, V5__...).
-- =====================================================================================

create table setores (
    id     bigint generated by default as identity,
    nome   varchar(120) not null,
    sigla  varchar(20)  not null,
    constraint pk_setores primary key (id),
    constraint uk_setores_sigla unique (sigla)
);

create table categorias (
    id         bigint generated by default as identity,
    nome       varchar(120) not null,
    descricao  varchar(500) not null,
    setor_id   bigint       not null,
    constraint pk_categorias primary key (id),
    constraint fk_categorias_setor foreign key (setor_id) references setores (id)
);

create table usuarios (
    id         bigint generated by default as identity,
    nome       varchar(120) not null,
    email      varchar(160) not null,
    matricula  varchar(30)  not null,
    tipo       varchar(20)  not null,
    setor_id   bigint,
    constraint pk_usuarios primary key (id),
    constraint uk_usuarios_email unique (email),
    constraint fk_usuarios_setor foreign key (setor_id) references setores (id),
    constraint ck_usuarios_tipo check (tipo in ('SOLICITANTE', 'TECNICO'))
);

create table chamados (
    id               bigint generated by default as identity,
    titulo           varchar(150)  not null,
    descricao        varchar(2000) not null,
    local            varchar(120)  not null,
    prioridade       varchar(20)   not null,
    status           varchar(20)   not null,
    data_abertura    timestamp     not null,
    data_fechamento  timestamp,
    solucao          varchar(2000),
    solicitante_id   bigint        not null,
    categoria_id     bigint        not null,
    tecnico_id       bigint,
    constraint pk_chamados primary key (id),
    constraint fk_chamados_solicitante foreign key (solicitante_id) references usuarios (id),
    constraint fk_chamados_categoria   foreign key (categoria_id)   references categorias (id),
    constraint fk_chamados_tecnico     foreign key (tecnico_id)     references usuarios (id),
    constraint ck_chamados_prioridade  check (prioridade in ('BAIXA', 'MEDIA', 'ALTA')),
    constraint ck_chamados_status      check (status in ('ABERTO', 'EM_ATENDIMENTO', 'RESOLVIDO', 'CANCELADO'))
);

create table interacoes (
    id          bigint generated by default as identity,
    texto       varchar(2000) not null,
    data_hora   timestamp     not null,
    chamado_id  bigint        not null,
    autor_id    bigint        not null,
    constraint pk_interacoes primary key (id),
    constraint fk_interacoes_chamado foreign key (chamado_id) references chamados (id),
    constraint fk_interacoes_autor   foreign key (autor_id)   references usuarios (id)
);

-- Indices de apoio aos filtros e a navegacao pelas chaves estrangeiras
create index idx_categorias_setor_id     on categorias (setor_id);
create index idx_usuarios_setor_id       on usuarios (setor_id);
create index idx_usuarios_tipo           on usuarios (tipo);
create index idx_chamados_categoria_id   on chamados (categoria_id);
create index idx_chamados_solicitante_id on chamados (solicitante_id);
create index idx_chamados_tecnico_id     on chamados (tecnico_id);
create index idx_chamados_status         on chamados (status);
create index idx_chamados_prioridade     on chamados (prioridade);
create index idx_chamados_data_abertura  on chamados (data_abertura);
create index idx_interacoes_chamado_id   on interacoes (chamado_id);
create index idx_interacoes_autor_id     on interacoes (autor_id);
